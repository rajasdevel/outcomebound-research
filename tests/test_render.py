    def test_main_is_idempotent(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            root = build_repo(Path(tmp))
            first = {rel: (root / rel).read_text(encoding="utf-8") for rel in render.render_all(root)}
            self.assertEqual(quiet_main("--root", str(root)), 0)
            self.assertEqual(first, {rel: (root / rel).read_text(encoding="utf-8") for rel in first})
            out = io.StringIO()
            with contextlib.redirect_stdout(out):
                self.assertEqual(render.main(["--root", str(root)]), 0)
            self.assertIn("0 written", out.getvalue())

