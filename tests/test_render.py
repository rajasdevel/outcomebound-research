def quiet_main(*args: str) -> int:
    with contextlib.redirect_stdout(io.StringIO()), contextlib.redirect_stderr(io.StringIO()):
        return render.main(list(args))


def card(**changes: object) -> dict:
    data = copy.deepcopy(FIXTURE_CARD)
    data.update(changes)
    return data


def field(block: str, name: str) -> str:
    """The value of one row of a card block."""
    prefix = f"| {name} | "
    return next(line for line in block.split("\n") if line.startswith(prefix))[len(prefix):-2]


