class RenderLinkSafetyTest(unittest.TestCase):
    MODEL = "models/example-lab/example-model-1.md"

    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.root = Path(self._tmp.name) / "repo"
        self.outside = Path(self._tmp.name) / "outside"
        self.outside.mkdir()
        build_repo(self.root)
        # Make every generated file stale, so a render has something to write.
        stale = layout.CARD_BEGIN + layout.CARD_END + layout.MODELS_BEGIN + layout.MODELS_END
        for rel in (layout.MODELS_README, layout.TIERS_MD, self.MODEL):
            (self.root / rel).write_text("---\n---\n" + stale, encoding="utf-8")

    def stale(self, rel: str) -> bool:
        return (self.root / rel).read_text(encoding="utf-8").startswith("---\n---\n")

    def test_a_linked_output_file_is_refused_and_its_target_left_alone(self) -> None:
        target = self.outside / "target.txt"
        target.write_text("keep me\n", encoding="utf-8")
        (self.root / layout.TIERS_MD).unlink()
        os.symlink(target, self.root / layout.TIERS_MD)
        self.assertEqual(quiet_main("--root", str(self.root)), 1)
        self.assertEqual(target.read_text(encoding="utf-8"), "keep me\n")
        self.assertTrue((self.root / layout.TIERS_MD).is_symlink())
        self.assertTrue(self.stale(layout.MODELS_README), "nothing is written when one destination is refused")
        self.assertTrue(self.stale(self.MODEL))

    def test_a_linked_model_file_is_refused_and_nothing_else_written(self) -> None:
        target = self.outside / "target.txt"
        target.write_text(layout.CARD_BEGIN + layout.CARD_END, encoding="utf-8")
        (self.root / self.MODEL).unlink()
        os.symlink(target, self.root / self.MODEL)
        self.assertEqual(quiet_main("--root", str(self.root)), 1)
        self.assertEqual(target.read_text(encoding="utf-8"), layout.CARD_BEGIN + layout.CARD_END)
        self.assertTrue(self.stale(layout.TIERS_MD))

    def test_a_dangling_link_at_an_output_file_is_refused(self) -> None:
        (self.root / layout.TIERS_MD).unlink()
        os.symlink(self.outside / "not-yet", self.root / layout.TIERS_MD)
        self.assertEqual(quiet_main("--root", str(self.root)), 1)
        self.assertFalse((self.outside / "not-yet").exists())

    def test_a_linked_output_folder_is_refused_and_its_target_left_alone(self) -> None:
        shutil.rmtree(self.root / "applications")
        os.symlink(self.outside, self.root / "applications")
        self.assertEqual(quiet_main("--root", str(self.root)), 1)
        self.assertEqual(list(self.outside.iterdir()), [])

    def test_a_link_swapped_in_after_the_check_is_still_not_followed(self) -> None:
        target = self.outside / "target.txt"
        target.write_text("keep me\n", encoding="utf-8")
        real = render.safefs.refuse_links
        calls = []

        def swap(root: Path, rel: str, folder: bool = False) -> None:
            real(root, rel, folder)
            calls.append(rel)
            if len(calls) == 4:  # every check has passed; put a link where the last file goes
                (root / rel).unlink()
                os.symlink(target, root / rel)

        with mock.patch.object(render.safefs, "refuse_links", swap):
            self.assertEqual(quiet_main("--root", str(self.root)), 1)
        self.assertEqual(calls[-1], layout.TIERS_MD)
        self.assertEqual(target.read_text(encoding="utf-8"), "keep me\n")

    def test_a_plain_destination_is_replaced_in_place(self) -> None:
        self.assertEqual(quiet_main("--root", str(self.root)), 0)
        self.assertTrue((self.root / layout.TIERS_MD).read_text(encoding="utf-8").startswith("---\nlast_checked: 2026-10-03"))

    def test_a_missing_applications_folder_is_created(self) -> None:
        shutil.rmtree(self.root / "applications")
        self.assertEqual(quiet_main("--root", str(self.root)), 0)
        self.assertTrue((self.root / layout.TIERS_MD).is_file())


