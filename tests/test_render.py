class ReplaceBlockTest(unittest.TestCase):
    B, E = layout.CARD_BEGIN, layout.CARD_END

    def test_only_the_text_between_the_markers_changes(self) -> None:
        text = f"head\n{self.B}\nold\nolder\n{self.E}\ntail\n"
        self.assertEqual(render.replace_block(text, self.B, self.E, "new\n", "f"), f"head\n{self.B}\nnew\n{self.E}\ntail\n")

    def test_an_empty_pair_is_filled_and_the_result_is_stable(self) -> None:
        text = f"head\n{self.B}\n{self.E}\ntail\n"
        once = render.replace_block(text, self.B, self.E, "x\n", "f")
        self.assertEqual(once, f"head\n{self.B}\nx\n{self.E}\ntail\n")
        self.assertEqual(render.replace_block(once, self.B, self.E, "x\n", "f"), once)

    def test_missing_doubled_and_misordered_markers_are_refused(self) -> None:
        for text in ("no markers\n", f"{self.B}\n", f"{self.E}\n{self.B}\n", f"{self.B}\n{self.E}\n{self.B}\n{self.E}\n"):
            with self.subTest(text=text):
                with self.assertRaisesRegex(ValueError, "^f: needs exactly one"):
                    render.replace_block(text, self.B, self.E, "x\n", "f")


